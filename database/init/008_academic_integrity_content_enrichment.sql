SET @academic_set_id = (
  SELECT id
  FROM regulation_set
  WHERE set_code = 'ACADEMIC_INTEGRITY_RESEARCH_FUNDS'
  LIMIT 1
);

DROP PROCEDURE IF EXISTS enrich_academic_regulation_content;
DELIMITER //
CREATE PROCEDURE enrich_academic_regulation_content(
  IN p_code VARCHAR(128),
  IN p_extra LONGTEXT
)
BEGIN
  SET @regulation_id = (
    SELECT id
    FROM regulation
    WHERE regulation_set_id = @academic_set_id
      AND code = p_code
      AND deleted = 0
    LIMIT 1
  );

  IF @regulation_id IS NOT NULL THEN
    SET @base_content = (
      SELECT CASE
        WHEN LOCATE('\n\n【规章正文补充】', content) > 0
          THEN SUBSTRING(content, 1, LOCATE('\n\n【规章正文补充】', content) - 1)
        ELSE content
      END
      FROM regulation_content
      WHERE regulation_id = @regulation_id
      LIMIT 1
    );

    SET @merged_content = CONCAT(@base_content, '\n\n【规章正文补充】\n', p_extra);

    UPDATE regulation_content
    SET content = @merged_content,
        plain_text = @merged_content,
        content_hash = SHA2(@merged_content, 256),
        updated_at = CURRENT_TIMESTAMP
    WHERE regulation_id = @regulation_id;
  END IF;
END//
DELIMITER ;

