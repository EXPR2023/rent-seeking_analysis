SET @academic_set_id = (
  SELECT id
  FROM regulation_set
  WHERE set_code = 'ACADEMIC_INTEGRITY_RESEARCH_FUNDS'
  LIMIT 1
);

DROP PROCEDURE IF EXISTS seed_academic_regulation;
DELIMITER //
CREATE PROCEDURE seed_academic_regulation(
  IN p_code VARCHAR(128),
  IN p_title VARCHAR(255),
  IN p_type_code VARCHAR(64),
  IN p_department VARCHAR(128),
  IN p_effective_date DATE,
  IN p_scope VARCHAR(500),
  IN p_content LONGTEXT
)
BEGIN
  INSERT INTO regulation (
    regulation_set_id, title, code, type_code, publish_department, effective_date, expiry_date,
    applicable_scope, status, analysis_status, created_by, updated_by
  )
  VALUES (
    @academic_set_id, p_title, p_code, p_type_code, p_department, p_effective_date, NULL,
    p_scope, 'ACTIVE', 'NOT_ANALYZED', @admin_id, @admin_id
  )
  ON DUPLICATE KEY UPDATE
    title = VALUES(title),
    type_code = VALUES(type_code),
    publish_department = VALUES(publish_department),
    effective_date = VALUES(effective_date),
    applicable_scope = VALUES(applicable_scope),
    status = VALUES(status),
    analysis_status = VALUES(analysis_status),
    updated_by = VALUES(updated_by),
    updated_at = CURRENT_TIMESTAMP,
    deleted = 0;

  SET @seed_regulation_id = (
    SELECT id
    FROM regulation
    WHERE regulation_set_id = @academic_set_id
      AND code = p_code
      AND deleted = 0
    LIMIT 1
  );

  INSERT INTO regulation_content (regulation_id, content, plain_text, content_hash)
  VALUES (@seed_regulation_id, p_content, p_content, SHA2(p_content, 256))
  ON DUPLICATE KEY UPDATE
    content = VALUES(content),
    plain_text = VALUES(plain_text),
    content_hash = VALUES(content_hash),
    updated_at = CURRENT_TIMESTAMP;
END//
DELIMITER ;

